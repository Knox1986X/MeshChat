package org.meshchat.lab.security

import android.hardware.biometrics.BiometricPrompt
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyInfo
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import android.security.keystore.UserNotAuthenticatedException
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.security.ProviderException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.SecretKeyFactory
import javax.crypto.spec.GCMParameterSpec

/**
 * Unintegrated hardware wrapping adapter; NOT a vault or full lock manager.
 * No network or production signing keys. Uses platform AES-GCM, not custom crypto.
 * This class must run on a serialized security worker, never concurrently with
 * alias deletion/replacement. Alias is installation-local, never caller IPC input.
 */
internal class AndroidKeyProtector(private val alias: String) {
    init {
        require(ALIAS_PATTERN.matches(alias))
    }

    enum class EnrollmentPolicy { STRONGBOX_REQUIRED, TEE_EXPLICITLY_ALLOWED }
    enum class HardwareLevel { STRONGBOX, TEE, LEGACY_HARDWARE_UNSPECIFIED }
    enum class Failure {
        ALIAS_EXISTS, MISSING_KEY, STRONGBOX_UNAVAILABLE, SOFTWARE_KEY_REJECTED,
        AUTH_REQUIRED, KEY_INVALIDATED, INVALID_INPUT, INTEGRITY_OR_PROVIDER_FAILURE,
        OPERATION_CLOSED, KEY_POLICY_MISMATCH,
    }
    class ProtectionException(val failure: Failure) : Exception(failure.name)

    /**
     * No automatic fallback. Call TEE_EXPLICITLY_ALLOWED only after explicit UX
     * decision; no key is replaced/deleted when an existing alias is encountered.
     * Biometric enrollment must exist. Credential/PIN fallback is NOT implemented.
     */
    fun create(policy: EnrollmentPolicy): HardwareLevel = platformCall {
        val store = store()
        if (store.containsAlias(alias)) fail(Failure.ALIAS_EXISTS)
        val spec = KeyGenParameterSpec.Builder(
            alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setKeySize(256)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setRandomizedEncryptionRequired(true)
            .setUserAuthenticationRequired(true)
            .setInvalidatedByBiometricEnrollment(true)
            .setIsStrongBoxBacked(policy == EnrollmentPolicy.STRONGBOX_REQUIRED)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            spec.setUserAuthenticationParameters(0, KeyProperties.AUTH_BIOMETRIC_STRONG)
        } else {
            @Suppress("DEPRECATION")
            spec.setUserAuthenticationValidityDurationSeconds(-1)
        }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        generator.init(spec.build())
        generator.generateKey()
        try {
            val level = hardwareLevel()
            if (policy == EnrollmentPolicy.STRONGBOX_REQUIRED &&
                Build.VERSION.SDK_INT >= Build.VERSION_CODES.S &&
                level != HardwareLevel.STRONGBOX
            ) fail(Failure.KEY_POLICY_MISMATCH)
            level
        } catch (failure: ProtectionException) {
            // A just-created unsupported key is never retained as a fallback.
            store.deleteEntry(alias)
            throw failure
        }
    }

    fun hardwareLevel(): HardwareLevel = platformCall {
        val key = loadKey()
        val factory = SecretKeyFactory.getInstance(key.algorithm, PROVIDER)
        val info = factory.getKeySpec(key, KeyInfo::class.java) as KeyInfo
        if (!info.isUserAuthenticationRequired || info.keySize != 256) {
            fail(Failure.KEY_POLICY_MISMATCH)
        }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            when (info.securityLevel) {
                KeyProperties.SECURITY_LEVEL_STRONGBOX -> HardwareLevel.STRONGBOX
                KeyProperties.SECURITY_LEVEL_TRUSTED_ENVIRONMENT -> HardwareLevel.TEE
                else -> fail(Failure.SOFTWARE_KEY_REJECTED)
            }
        } else {
            // API29/30 cannot reliably report TEE vs StrongBox via this API.
            @Suppress("DEPRECATION")
            if (!info.isInsideSecureHardware) fail(Failure.SOFTWARE_KEY_REJECTED)
            HardwareLevel.LEGACY_HARDWARE_UNSPECIFIED
        }
    }

    /** Fresh IV is generated by AndroidKeyStore, never by app timestamps/counters. */
    fun beginWrap(vaultId: ByteArray): WrapOperation = platformCall {
        hardwareLevel() // Recheck instead of trusting persisted metadata.
        val aad = aad(vaultId)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, loadKey())
        WrapOperation(cipher, aad)
    }

    /** Malformed wrappers rejected before Keystore/decryption; auth still needed. */
    fun beginUnwrap(vaultId: ByteArray, wrapped: ByteArray): UnwrapOperation = platformCall {
        if (wrapped.size != WRAPPED_BYTES || wrapped[0] != VERSION) fail(Failure.INVALID_INPUT)
        hardwareLevel()
        val aad = aad(vaultId)
        val iv = wrapped.copyOfRange(1, 13)
        val ciphertext = wrapped.copyOfRange(13, WRAPPED_BYTES)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, loadKey(), GCMParameterSpec(128, iv))
        UnwrapOperation(cipher, aad, ciphertext)
    }

    // Not exposed to UI yet: deleting a wrapping key makes associated data
    // unrecoverable only if no other wrappers/backups exist. Never call on error.
    fun deleteAfterExplicitUserDecision() = platformCall { store().deleteEntry(alias) }

    private fun aad(vaultId: ByteArray): ByteArray {
        if (vaultId.size != 16) fail(Failure.INVALID_INPUT)
        return DOMAIN + alias.toByteArray(Charsets.US_ASCII) + byteArrayOf(VERSION) + vaultId
    }

    private fun store(): KeyStore = KeyStore.getInstance(PROVIDER).apply { load(null) }

    private fun loadKey(): SecretKey =
        (store().getKey(alias, null) as? SecretKey) ?: fail(Failure.MISSING_KEY)

    /**
     * Supply cryptoObject to OS BiometricPrompt.authenticate(). Authentication
     * is enforced by Keystore doFinal(), not a caller-supplied `authenticated` bool.
     * OS prompt cancellation/lock must also call close() and cancel its signal.
     */
    class WrapOperation internal constructor(
        private var cipher: Cipher?,
        private val aad: ByteArray,
    ) : AutoCloseable {
        @get:Synchronized
        val cryptoObject: BiometricPrompt.CryptoObject
            get() = BiometricPrompt.CryptoObject(cipher ?: fail(Failure.OPERATION_CLOSED))

        /** Takes ownership of the input key and overwrites it even on failure. */
        @Synchronized
        fun finishConsumingKeyAfterAuthentication(key: ByteArray): ByteArray = try {
            platformCall {
                if (key.size != KEY_BYTES) fail(Failure.INVALID_INPUT)
                val operation = cipher ?: fail(Failure.OPERATION_CLOSED)
                try {
                    operation.updateAAD(aad)
                    val encrypted = operation.doFinal(key)
                    val iv = operation.iv
                    if (iv.size != 12 || encrypted.size != 48) fail(Failure.INTEGRITY_OR_PROVIDER_FAILURE)
                    byteArrayOf(VERSION) + iv + encrypted
                } finally {
                    close()
                }
            }
        } finally {
            key.fill(0)
            close()
        }

        @Synchronized
        override fun close() {
            cipher = null
            aad.fill(0)
        }
    }

    class UnwrapOperation internal constructor(
        private var cipher: Cipher?,
        private val aad: ByteArray,
        private val ciphertext: ByteArray,
    ) : AutoCloseable {
        @get:Synchronized
        val cryptoObject: BiometricPrompt.CryptoObject
            get() = BiometricPrompt.CryptoObject(cipher ?: fail(Failure.OPERATION_CLOSED))

        /** Returned plaintext key is caller-owned: keep out of Strings/Bundle/logs. */
        @Synchronized
        fun finishAfterAuthentication(): ByteArray = platformCall {
            val operation = cipher ?: fail(Failure.OPERATION_CLOSED)
            try {
                operation.updateAAD(aad)
                val key = operation.doFinal(ciphertext)
                if (key.size != KEY_BYTES) {
                    key.fill(0)
                    fail(Failure.INTEGRITY_OR_PROVIDER_FAILURE)
                }
                key
            } finally {
                close()
            }
        }

        @Synchronized
        override fun close() {
            cipher = null
            aad.fill(0)
            ciphertext.fill(0)
        }
    }

    companion object {
        private const val PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val KEY_BYTES = 32
        private const val WRAPPED_BYTES = 61 // version1 + IV12 + encrypted key32 + tag16
        private const val VERSION: Byte = 1
        private val DOMAIN = "MESHCHAT-LAB-VAULT-WRAP-V1\u0000".toByteArray(Charsets.US_ASCII)
        private val ALIAS_PATTERN = Regex("meshchat\\.lab\\.wrap\\.v1\\.[a-f0-9]{32}")

        private fun fail(failure: Failure): Nothing = throw ProtectionException(failure)

        private inline fun <T> platformCall(block: () -> T): T = try {
            block()
        } catch (error: ProtectionException) {
            throw error
        } catch (_: KeyPermanentlyInvalidatedException) {
            fail(Failure.KEY_INVALIDATED)
        } catch (_: UserNotAuthenticatedException) {
            fail(Failure.AUTH_REQUIRED)
        } catch (_: StrongBoxUnavailableException) {
            fail(Failure.STRONGBOX_UNAVAILABLE)
        } catch (_: GeneralSecurityException) {
            // Wrong AAD/tag, missing enrollment, provider failure: no sensitive details.
            fail(Failure.INTEGRITY_OR_PROVIDER_FAILURE)
        } catch (_: ProviderException) {
            fail(Failure.INTEGRITY_OR_PROVIDER_FAILURE)
        } catch (_: SecurityException) {
            fail(Failure.INTEGRITY_OR_PROVIDER_FAILURE)
        }
    }
}
