const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\p{N}\s.@-]/gu, ' ')

/** Взвешенный матч: длинные ключи ценнее коротких */
function score(text: string, keys: string[]): number {
  let total = 0
  for (const k of keys) {
    const key = norm(k).trim()
    if (!key) continue
    if (text.includes(key)) total += key.length * (key.includes(' ') ? 1.6 : 1)
  }
  return total
}

let ticketSeq = 4821

export function makeTicket() {
  ticketSeq += 1
  return { id: `MC-${ticketSeq}`, eta: 'до 12 часов' as const, severity: 'normal' as const }
}

export function botReply(input: string, ctx: BotContext): BotAnswer {
  const text = norm(input)

  if (!text.trim()) {
    return { text: 'Напиши вопрос — я рядом 🙂', chips: SUPPORT_CHIPS }
  }

  const ranked = RULES
    .map(r => ({ rule: r, s: score(text, r.keys) }))
    .filter(x => x.s > 0)
    .sort((a, b) => b.s - a.s)

  if (!ranked.length) {
    return {
      text:
        `Хм, не нашёл готового ответа на это 🤔\n\n` +
        `Могу помочь с: шифрованием, анонимностью, транспортами и обходом блокировок, установкой APK, звонками, ` +
        `группами, багами и настройками приватности.\n\n` +
        `Если вопрос не про это — скажи «оператор», и я создам тикет: ответит живой человек.`,
      chips: ['Создать тикет', 'Как работает шифрование?', 'Где скачать APK?'],
    }
  }

  const best = ranked[0].rule
  const answer = best.answer(ctx)

  return {
    text: answer,
    chips: best.chips ?? SUPPORT_CHIPS,
    delay: Math.min(900 + answer.length * 4, 2600),
    ticket: best.ticket ? makeTicket() : undefined,
  }
}
